% Training process
function [rmse,rmse_dynamic,Y]=func_train_attractor_with_lable(hyperpara_set,traindata,rng_num,testdata)

%%
rng(rng_num);   % random seed
drive_num=50; 
param_num=4;    % Number of bifurcation parameters
numCopies =1;   % Number of times that data needs to be replicated. 
% If the number of replication times is 1, the data remains unchanged
testdata = repmat(testdata, numCopies, 1);  

%%
eig_rho =hyperpara_set(1);   % spectral radius of the layer connection matrix
W_in_a = hyperpara_set(2);   % Range of the connection matrix between the input layer 
                             % and the hidden layer
a = hyperpara_set(3);        % Leakage rate
reg = hyperpara_set(4);      % Regularization coefficient
density =hyperpara_set(5);   % The density of the hiddenlayer connection matrix of RC
resSize =500;                % size of the reservoir  
initLen = 100;
trainLen=length(traindata(1,:))-1; % The length of training data
testLen = 2000;     % Predicted data length
inSize = 4;         % Input layer data dimension
outSize = 3;        % Output layer data dimension
nonliner_num=2;     % The RC neuron output function is modeled as a set of 
                    % linear and nonlinear (square terms)
%%
  indata=traindata;  % 4*14000
  X = zeros(nonliner_num*resSize+1,trainLen);  % F(x)=[x; x^2; 1]
  Yt = indata(1:outSize,2:trainLen+1);         % Forecast data corresponding
                                               % to target system data
%%
Win = (2.0*rand(resSize,inSize)-1.0)*W_in_a;
WW = zeros(resSize,resSize);  % Set the storage space for the hidden layer 
                              % connection matrix before it is processed
% Generate a symmetric sparse matrix WW
for i=1:resSize
    for j=i:resSize
            if (rand()<density)
             WW(i,j)=(2.0*rand()-1.0);
             WW(j,i)=WW(i,j);
            end
    end
end
rhoW = eigs(WW,1);          % Find the maximum eigenvalue
W = WW .* (eig_rho /rhoW);  % Scaling the adjacency matrix
x = zeros(resSize,1);       % Randomly initializes the state of hidden layer neurons
for t = 1:trainLen
    u = indata(:,t);        % Assign the variable data of training set time step t to u
    x = (1-a)*x + a*tanh( Win*u + W*x );  % Update the status of the RC node
    X(:,t) = [1;x;x.^2];               % Node state after RC hidden layer neuron output function
end
% Remove the initial step size of the RC prediction data and 
% the actual data of the corresponding target system
    X(:,1:initLen)=[];  % initLen = 100;
   Yt(:,1:initLen)=[];

% Randomizing the sequence of the iterative data of the corresponding variables
% helps to improve the generalization ability of RC prediction and prevent 
% the dependence of RC on time
rank=randperm( size(X,2) );   % Randomizing the sequence of the iterative 
% data of the corresponding variables helps to improve the generalization
% ability of RC prediction and prevent the dependence of RC on time
X=X(:, rank);   % Rearrange the columns of the matrix X using a randomly arranged index
Yt=Yt(:, rank); 
X_T = X';
% Train Wout with randomly scrambled data
Wout = Yt*X_T / (X*X_T + reg*eye(nonliner_num*resSize+1));

%%  Test
Y=zeros(4,param_num*testLen);     
rmse_dynamic=0;  

for j=0:param_num-1             % Generate predictive data for each parameter
    Y1= zeros(outSize,testLen); % Store the predicted tesLen length for each parameter
    x1=2*rand(resSize,1)-1;     % The RC hidden layer state is reinitialized
                            % when the data for each parameter is predicted
    Y1(1:3,1)=rand(3,1);
    Y1(4,1)=testdata(4,2000*j+1); 
    u=testdata(:,2000*j+1);       % Give u the first column of each parameter in the test set
   for t = 1:testLen-1
        x1 = (1-a)*x1 + a*tanh( Win*u + W*x1 ); % Renew neuron state
        y = Wout*[1;x1;x1.^2;];                 % Data generated by RC
        if t<=drive_num  % When the startup data is within the drive_num step,
                         % each step of the test data drives the next step
            u=testdata(:,2000*j+t+1);   
        else
            u = y;        % RC closes the loop to generate data
        end
        Y1(1:3,t+1) = y;  % The data generated by the system is collected as
                          % the next step in the system input data
        Y1(4,t+1)=testdata(4,2000*j+t+1);
        u(4,1)=testdata(4,2000*j+t+1);  % The last row of each attractor data, unchanged
   end        
 Y(:,2000*j+1:2000*j+2000)=Y1;
% The prediction error is calculated below
pre_num=1550;  % Calculate the average error between the start of the drive_num
               % duration and the pre_num duration
rmse_dynamic=rmse_dynamic+mean(abs(Y1(3,drive_num:drive_num+pre_num)-...
             testdata(3,2000*j+drive_num:2000*j+drive_num+pre_num)))+...
            mean(abs(Y1(2,drive_num:drive_num+pre_num)-...
            testdata(2,2000*j+drive_num:2000*j+drive_num+pre_num)))+...
            mean(abs(Y1(1,drive_num:drive_num+pre_num)-...
            testdata(1,2000*j+drive_num:2000*j+drive_num+pre_num)));
end
rmse=rmse_dynamic;
if isnan(rmse) || rmse>10
    rmse=10;
end
