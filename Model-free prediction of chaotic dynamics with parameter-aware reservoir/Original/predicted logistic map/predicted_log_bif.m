% predict logistic map bifurcation
clc;clear;
load('traindata.mat');
eig_rho =0.05;  % spectral radius of the layer connection matrix W
W_in_a = 1;     % Range of the connection matrix between the input layer 
                % and the hidden layer
a = 1;          % Leakage rate
reg = 1e-5;     % Regularization coefficient 
density =0.2;   % The density of the hiddenlayer connection matrix of RC 
% hyperpara_set=[eig_rho,W_in_a,a,reg,density];
rng(1);
resSize =100;   % size of the reservoir
initLen = 100;
trainLen=length(traindata(1,:))-1;       % The length of training data
inSize = 2;         % Input layer data dimension
outSize = 1;        % Output layer data dimension
nonliner_num=2;     % The RC neuron output function is modeled as a set of 
                    % linear and nonlinear (square terms)
%%
  indata=traindata;  % 2*8000
  X = zeros(nonliner_num*resSize+1,trainLen);  % F(x)=[x; x^2; 1]
  Yt = indata(1:outSize,2:trainLen+1);         % Forecast data corresponding to target system data
%%
Win = (2.0*rand(resSize,inSize)-1.0)*W_in_a;
WW = zeros(resSize,resSize);  % Set the storage space for the hidden layer 
                              % connection matrix before it is processed
for i=1:resSize
    for j=i:resSize
            if (rand()<density)
             WW(i,j)=(2.0*rand()-1.0);
             WW(j,i)=WW(i,j);
            end
    end
end
rhoW = eigs(WW,1);          % Find the maximum eigenvalue
W = WW .* (eig_rho /rhoW);  % Scaling the adjacency matrix
%% 训练 Wout
x=2*rand(resSize,1)-1;    % Randomly initializes the state of hidden layer neurons
for t = 1:trainLen
    u = indata(:,t);      % Give u column t of the input data 
    x = (1-a)*x + a*tanh( Win*u + W*x );  % Update the status of the RC node
    X(:,t) = [1;x;x.^2;];   % Node state after RC hidden layer neuron output function
end
% Remove the initial step size of the RC prediction data and 
% the actual data of the corresponding target system
    X(:,1:initLen)=[];  % initLen = 100;
   Yt(:,1:initLen)=[];
% Randomizing the sequence of the iterative data of the corresponding variables
% helps to improve the generalization ability of RC prediction and prevent 
% the dependence of RC on time
rank=randperm( size(X,2) );   % Randomizing the sequence of the iterative 
% data of the corresponding variables helps to improve the generalization
% ability of RC prediction and prevent the dependence of RC on time
X=X(:, rank);  % Rearrange the columns of the matrix X using a randomly arranged index
Yt=Yt(:, rank); 
X_T = X';
% Train Wout with randomly scrambled data
Wout = Yt*X_T / (X*X_T + reg*eye(nonliner_num*resSize+1));
%% predict logistic map bifurcation
predicted_logistic_bif=[];  

r=3.2:0.001:4;         % Range of bifurcation parameters
n_r=length(r);         % Number of bifurcation parameter r
testLen=5000;          % Predicted data length
y = Wout*[1;x;x.^2;];  
for k=1:n_r    % Generate bifurcation diagram data for each bifurcation parameter
    u(1,1)=y;  % Let the data generated by RC be the input for the next step
    u(2,1)=r(k);  % Add the corresponding bifurcation parameters to the RC input time series
    Y= zeros(outSize,testLen);  
    %% Warming up
    for t = 1:100  
        x= (1-a).*x + a.*tanh( Win*u + W*x );
        y = Wout*[1;x;x.^2;];  % Data generated by RC
        Y(:,t) = y;            % Save the output to the Y matrix
        u(1,1) = y;
        u(2,1)=r(k);           % Add a parameter label to the data
    end
    %% Predicting
     % The input time series of the first data to start the prediction is 
     % the output of the previous step of the RC
    for t = 1:testLen          
        x= (1-a).*x + a.*tanh( Win*u + W*x );  
        y = Wout*[1;x;x.^2;];  
        Y(:,t) = y;            
        u(1,1) = y;
        u(2,1)=r(k);
    end
    predicted_logistic_bif(k,:)=Y(:,end-500+1:end);  
    % Keep the last 500 dotted bifurcation plots for each bifurcation parameter
end
save('predicted_logistic_bif.mat','predicted_logistic_bif');
plot(r,predicted_logistic_bif,'k.','markersize',0.5);
hold on;
% Draw four vertical dotted lines, each representing the location of the 
% sampling point of the bifurcation parameter
a_values=[3.3, 3.5, 3.6, 3.8];  % The bifurcation parameter value 
                                % corresponding to each vertical line
posi=[0.02, 0.05, 0.02, 0.05];  % The location of each sampling point
% Draw multiple vertical lines and label them
for i=1:length(a_values)
    xline(a_values(i), '--b', 'LineWidth', 2); % Use a dashed blue line 
                                              % with a line width of 2
    % Add annotations with x values
    text(a_values(i), posi(i), ['a = ' num2str(a_values(i))], 'VerticalAlignment',...
        'bottom', 'HorizontalAlignment', 'right', 'FontSize', 15, 'Color', 'red');
end
